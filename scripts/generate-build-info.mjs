/**
 * Writes src/build-info.ts with the current short git SHA and ISO build date.
 * Runs automatically via the prebuild / prestart npm hooks.
 */
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

let commit = 'dev';
let message = '';
try {
  commit = execSync('git rev-parse --short HEAD', { cwd: root }).toString().trim();
  const raw = execSync('git log -1 --format=%B', { cwd: root }).toString().trim();
  // Merge commits look like "Merge pull request #N from branch\n\nOriginal subject"
  // Strip that preamble and use the original subject line instead.
  const mergeMatch = raw.match(/^Merge pull request #\d+ from \S+\n+(.+)/);
  message = (mergeMatch ? mergeMatch[1] : raw.split('\n')[0]).slice(0, 20).replace(/'/g, "\\'");
} catch {
  // not a git repo or git not available — keep defaults
}

const date = new Date().toISOString();

const content = `// Auto-generated by scripts/generate-build-info.mjs — do not edit manually
export const BUILD_INFO = {
  commit: '${commit}',
  message: '${message}',
  date: '${date}',
} as const;
`;

writeFileSync(join(root, 'src', 'build-info.ts'), content);
console.log(`build-info: commit=${commit} date=${date}`);
